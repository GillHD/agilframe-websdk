const DICTIONARIES: Record<Locale, Dict> = { ru, en };

export class I18n {
  private locale: Locale;

  constructor(locale: Locale = 'ru') {
    this.locale = locale;
  }

  get current(): Locale {
    return this.locale;
  }

  setLocale(locale: Locale): void {
    this.locale = locale;
  }

  t(key: I18nKey, vars?: Record<string, string | number>): string {
    const dict = DICTIONARIES[this.locale] ?? ru;
    let value: string = dict[key] ?? ru[key] ?? key;
    if (vars) {
      for (const [name, replacement] of Object.entries(vars)) {
        value = value.split(`{${name}}`).join(String(replacement));
      }
    }
    return value;
  }

  /** "1 участник" / "3 участника" for the ru locale, simple plural for en. */
  plural(count: number, one: I18nKey, many: I18nKey, few = many): string {
    if (this.locale === 'en') return `${count} ${this.t(count === 1 ? one : many)}`;
    const mod10 = count % 10;
    const mod100 = count % 100;
    if (mod10 === 1 && mod100 !== 11) return `${count} ${this.t(one)}`;
    if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return `${count} ${this.t(few)}`;
    return `${count} ${this.t(many)}`;
  }
}

