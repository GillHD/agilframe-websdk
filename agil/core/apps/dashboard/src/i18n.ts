let resolved: Locale = 'ru';

function readLocale(): Locale {
  try {
    const fromQuery = new URLSearchParams(window.location.search).get('lang');
    if (fromQuery === 'en' || fromQuery === 'ru') return fromQuery;
    const stored = window.localStorage.getItem(STORAGE_KEY);
    if (stored === 'en' || stored === 'ru') return stored;
  } catch {
    /* storage can be unavailable (private mode / disabled cookies) */
  }
  return 'ru';
}

export const locale: Locale = readLocale();
resolved = locale;

export function currentLocale(): Locale {
  return resolved;
}

export function isEnglish(): boolean {
  return resolved === 'en';
}

export function applyDocumentLocale(): void {
  if (typeof document === 'undefined') return;
  document.documentElement.lang = resolved;
  if (typeof document.documentElement.dir !== 'string') document.documentElement.dir = 'ltr';
}

/** Stores the choice and reloads so every module sees the same locale. */
export function setLocale(next: Locale): void {
  try {
    window.localStorage.setItem(STORAGE_KEY, next);
  } catch {
    /* ignore */
  }
  try {
    const url = new URL(window.location.href);
    url.searchParams.set('lang', next);
    window.location.replace(url.toString());
  } catch {
    window.location.reload();
  }
}

export function toggleLocale(): void {
  setLocale(resolved === 'en' ? 'ru' : 'en');
}

/**
 * Translates `key`, falling back to Russian (the product default) when the
 * English dictionary has no entry. `{name}` placeholders are interpolated.
 */
export function t(key: MessageKey, vars?: Record<string, string | number>): string {
  const dictionary: Record<MessageKey, string> = resolved === 'en' ? en : ru;
  let value = dictionary[key] ?? ru[key] ?? key;
  if (vars) {
    for (const [name, replacement] of Object.entries(vars)) {
      value = value.replaceAll(`{${name}}`, () => String(replacement));
    }
  }
  return value;
}

/** Language switch label (points at the *other* locale). */
export function languageLabel(): string {
  return resolved === 'en' ? 'RU' : 'EN';
}

export function languageSwitchTitle(): string {
  // The switch label stays in the current UI language; the button itself shows
  // the target locale ("EN" / "RU").
  return resolved === 'en' ? 'Switch to Russian' : 'Переключить на английский';
}

